# Problem 2
# Count and print how many numbers are odd in the list (a number is odd if it's not divisible by 2).
numbers = [8, 3, 12, 7, 4, 11]
print(numbers)
counter = 0
for number in numbers:
    if number % 2 != 0:
        counter += 1
print("Number of odd numbers:", counter)       



